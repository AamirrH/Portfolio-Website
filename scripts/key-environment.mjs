import sharp from 'sharp';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { chromaKey } from './chroma-key.mjs';
import { components } from './asset-components.mjs';
const root = new URL('../',import.meta.url);
const report = {};
const assets = {};
async function keyed(name) {
 const {data,info}=await sharp(await readFile(new URL(`assets-src/${name}-raw.png`,root))).ensureAlpha().raw().toBuffer({resolveWithObject:true});
 chromaKey(data,info.width,info.height,{removeWatermark:false});
 return {data,info};
}
async function exportSprite(data,info,box,folder,name,maxHeight=700) {
 const {area,...crop}=box;
 const result=await sharp(data,{raw:info}).extract(crop).resize({height:Math.min(crop.height,maxHeight)}).webp({quality:88,alphaQuality:100}).toBuffer({resolveWithObject:true});
 await mkdir(new URL(`public/assets/${folder}/`,root),{recursive:true});
 await writeFile(new URL(`public/assets/${folder}/${name}.webp`,root),result.data);
 return {src:`/assets/${folder}/${name}.webp`,aspect:result.info.width/result.info.height,bytes:result.data.length,crop};
}
const {data,info}=await keyed('props');
for(let y=Math.floor(info.height*.85);y<info.height;y++) for(let x=Math.floor(info.width*.945);x<info.width;x++) data[(y*info.width+x)*4+3]=0;
// Twelve spatial groups retain disconnected chair/rack pieces from the component pass.
const groups=[
 ['parisian-lamp',0,.0,.18,.64],['modern-lamp',.19,0,.37,.64],['topiary',.32,.18,.46,.64],
 ['bench',.49,.04,.74,.34],['bistro',.75,.04,.98,.34],
 ['hydrant',.48,.38,.57,.63],['trash-bin',.60,.38,.71,.63],['bike-rack',.74,.38,.97,.63],
 ['kiosk',.04,.65,.30,.98],['bollards',.33,.70,.56,.98],['scooter',.58,.70,.80,.98],['phone-booth',.83,.65,.95,.98]
];
const blobs=components(data,info.width,info.height,true).filter(b=>b.area>100);
for(const [name,x0,y0,x1,y1] of groups) {
 const found=blobs.filter(b=>{const x=(b.left+b.width/2)/info.width,y=(b.top+b.height/2)/info.height;return x>=x0&&x<x1&&y>=y0&&y<y1;});
 if(!found.length) throw new Error(`Missing sprite ${name}`);
 const left=Math.min(...found.map(b=>b.left)),top=Math.min(...found.map(b=>b.top));
 const right=Math.max(...found.map(b=>b.left+b.width)),bottom=Math.max(...found.map(b=>b.top+b.height));
 const isolated=Buffer.alloc(data.length);
 for(const blob of found) for(const pixel of blob.pixels) data.copy(isolated,pixel*4,pixel*4,pixel*4+4);
 assets[name]=await exportSprite(isolated,info,{left,top,width:right-left,height:bottom-top},'props',name);
}
report.props=assets;
const neighbor=await keyed('neighbors');
// The source has a drawn baseline connecting the two facades. Remove that line
// and the green padding below it before finding the two building components.
const baseline=Math.floor(neighbor.info.height*.948);
neighbor.data.fill(0,baseline*neighbor.info.width*4);
for(const [name,left,width] of [['left',0,Math.floor(neighbor.info.width*.40)],['right',Math.floor(neighbor.info.width*.64),neighbor.info.width-Math.floor(neighbor.info.width*.64)]]) {
 const crop={left,top:0,width,height:baseline};
 const pixels=await sharp(neighbor.data,{raw:neighbor.info}).extract(crop).raw().toBuffer({resolveWithObject:true});
 // Replace the small sparkle over the lower right wall with a nearby wall sample.
 if(name==='right') for(let y=Math.floor(pixels.info.height*.94);y<pixels.info.height;y++) for(let x=Math.floor(pixels.info.width*.83);x<Math.floor(pixels.info.width*.94);x++) {
   const dst=(y*pixels.info.width+x)*4,src=((y-Math.floor(pixels.info.height*.075))*pixels.info.width+x)*4;
   pixels.data.copy(pixels.data,dst,src,src+4);
 }
 const box=components(pixels.data,pixels.info.width,pixels.info.height)[0];
 report[name]=await exportSprite(pixels.data,pixels.info,box,'neighbors',name,900);
}
await writeFile(new URL('public/assets/props/asset-report.json',root),JSON.stringify(report,null,2));
await writeFile(new URL('src/data/propAssets.ts',root),'// Generated by scripts/key-environment.mjs.\nexport const propAssets = '+JSON.stringify(Object.fromEntries(Object.entries(assets).map(([k,v])=>[k,{src:v.src,aspect:v.aspect} ])),null,2)+' as const;\n');
console.log(JSON.stringify(report,null,2));

const skyline=await keyed('skyline');
// Exclude the two low outer stubs and the sparkle; the central city is seamless
// when paired with a mirrored copy. Retain its common bottom contact edge.
const cityCrop={left:Math.round(skyline.info.width*.085),top:0,width:Math.round(skyline.info.width*.828),height:skyline.info.height};
const city=await sharp(skyline.data,{raw:skyline.info}).extract(cityCrop).png().toBuffer();
const trimmed=await sharp(city).trim({threshold:0}).resize({width:1800}).raw().toBuffer({resolveWithObject:true});
await mkdir(new URL('public/assets/skyline/',root),{recursive:true});
for(const [depth,brightness,saturation] of [['far',1.5,.3],['mid',1.1,.65],['near',.85,.85]]) {
 await sharp(trimmed.data,{raw:trimmed.info}).modulate({brightness,saturation}).webp({quality:88,alphaQuality:100}).toFile(new URL(`public/assets/skyline/${depth}.webp`,root).pathname.replace(/^\/(\w:)/,'$1'));
}
await writeFile(new URL('public/assets/skyline/asset-report.json',root),JSON.stringify({source:'assets-src/skyline-raw.png',crop:cityCrop,width:trimmed.info.width,height:trimmed.info.height,variants:['far','mid','near']},null,2));
